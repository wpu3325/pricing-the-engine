// Generates src/data/*.js from the canonical JSON in data/. Browsers load plain
// ES modules everywhere; no import attributes needed. test/data-sync.test.js
// fails if the generated modules drift from the JSON.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pairs = [
  ['data/model_catalog.json', 'src/data/model_catalog.js', 'MODEL_CATALOG'],
  ['data/workload_presets.json', 'src/data/workload_presets.js', 'WORKLOAD_PRESETS'],
  ['data/gpu_skus.json', 'src/data/gpu_skus.js', 'GPU_SKUS'],
];
for (const [src, dst, name] of pairs) {
  const json = readFileSync(join(root, src), 'utf8');
  JSON.parse(json); // validate
  const body = `// GENERATED by scripts/sync_data.mjs from ${src}. Do not edit by hand.\nexport const ${name} = ${json.trim()};\n`;
  writeFileSync(join(root, dst), body);
  console.log(`wrote ${dst}`);
}
